def _make_toc_para_xml(toc_level: int, text: str, bm_name: str) -> bytes:
    """
    Строит XML одной записи содержания:
      <w:p>
        <w:pPr><w:pStyle w:val="12|20"/></w:pPr>
        <w:hyperlink w:anchor="bm_name" w:history="1">
          <w:r> ...text... </w:r>
          <w:r> ...tab... </w:r>
          PAGEREF field (begin+instr+sep+"?"+end)
        </w:hyperlink>
      </w:p>
    """
    style_id = '12' if toc_level == 1 else '20'  # toc 1 / toc 2
    esc = (text.replace('&', '&amp;')
               .replace('<', '&lt;')
               .replace('>', '&gt;')
               .replace('"', '&quot;'))
    xml = (
        f'<w:p xmlns:w="{W_NS}">'
        f'<w:pPr><w:pStyle w:val="{style_id}"/></w:pPr>'
        f'<w:hyperlink w:anchor="{bm_name}" w:history="1">'
          # --- текст ---
          f'<w:r>'
            f'<w:rPr><w:rStyle w:val="af8"/><w:noProof/></w:rPr>'
            f'<w:t xml:space="preserve">{esc}</w:t>'
          f'</w:r>'
          # --- табуляция ---
          f'<w:r>'
            f'<w:rPr><w:noProof/><w:webHidden/></w:rPr>'
            f'<w:tab/>'
          f'</w:r>'
          # --- PAGEREF: begin ---
          f'<w:r>'
            f'<w:rPr><w:noProof/><w:webHidden/></w:rPr>'
            f'<w:fldChar w:fldCharType="begin"/>'
          f'</w:r>'
          # --- PAGEREF: instrText ---
          f'<w:r>'
            f'<w:rPr><w:noProof/><w:webHidden/></w:rPr>'
            f'<w:instrText xml:space="preserve"> PAGEREF {bm_name} \\h </w:instrText>'
          f'</w:r>'
          # --- PAGEREF: separate ---
          f'<w:r>'
            f'<w:rPr><w:noProof/><w:webHidden/></w:rPr>'
            f'<w:fldChar w:fldCharType="separate"/>'
          f'</w:r>'
          # --- placeholder номера страницы ---
          f'<w:r>'
            f'<w:rPr><w:noProof/><w:webHidden/></w:rPr>'
            f'<w:t>?</w:t>'
          f'</w:r>'
          # --- PAGEREF: end ---
          f'<w:r>'
            f'<w:rPr><w:noProof/><w:webHidden/></w:rPr>'
            f'<w:fldChar w:fldCharType="end"/>'
          f'</w:r>'
        f'</w:hyperlink>'
        f'</w:p>'
    )
    return xml.encode('utf-8')


def patch_docx(docx_path: Path, headings: list):
    """
    Постобработка .docx:
    1. styles.xml  — добавляем outlineLvl=0 к «Приложение-заголовок»
    2. document.xml — пересобираем кеш TOC
    3. settings.xml — включаем updateFields
    """
    # Читаем все файлы из ZIP
    files: dict[str, bytes] = {}
    with zipfile.ZipFile(docx_path, 'r') as z:
        for name in z.namelist():
            files[name] = z.read(name)

    # ── 1. styles.xml: добавить outlineLvl стилю -4 (Приложение-заголовок) ──
    styles_root = etree.fromstring(files['word/styles.xml'])
    for style in styles_root.iter(f'{{{W_NS}}}style'):
        if style.get(f'{{{W_NS}}}styleId') == '-4':
            pPr = style.find(f'{{{W_NS}}}pPr')
            if pPr is None:
                pPr = etree.SubElement(style, f'{{{W_NS}}}pPr')
            ol = pPr.find(f'{{{W_NS}}}outlineLvl')
            if ol is None:
                ol = etree.SubElement(pPr, f'{{{W_NS}}}outlineLvl')
            ol.set(f'{{{W_NS}}}val', '0')   # level 0 → TOC depth 1
            break
    files['word/styles.xml'] = etree.tostring(
        styles_root, xml_declaration=True, encoding='UTF-8', standalone=True
    )

    # ── 2. document.xml: пересобираем кеш TOC ────────────────────────────────
    doc_root = etree.fromstring(files['word/document.xml'])
    body_el  = doc_root.find(f'{{{W_NS}}}body')
    children = list(body_el)

    # Находим первый абзац с TOC instrText (стиль 12, позиция ~125)
    toc_field_para_idx = None
    toc_end_para_idx   = None
    for i, child in enumerate(children):
        if child.tag != f'{{{W_NS}}}p':
            continue
        # Ищем instrText с "TOC"
        for instr in child.iter(f'{{{W_NS}}}instrText'):
            if instr.text and 'TOC' in instr.text and '\\o' in instr.text:
                toc_field_para_idx = i
                # Обновляем инструкцию — добавляем \t для Приложение-заголовок
                instr.text = ' TOC \\o "1-2" \\h \\z \\u \\t "Приложение-заголовок,1" '
                break
        if toc_field_para_idx is not None:
            break

    if toc_field_para_idx is None:
        print('WARN: TOC field not found — contents not rebuilt')
    else:
        # Находим параграф только с fldChar end (TOC end) — первый после toc_field_para_idx
        # у которого нет instrText, только fldChar end
        for i in range(toc_field_para_idx + 1, min(toc_field_para_idx + 50, len(children))):
            child = children[i]
            if child.tag != f'{{{W_NS}}}p':
                continue
            has_end = any(
                fc.get(f'{{{W_NS}}}fldCharType') == 'end'
                for fc in child.iter(f'{{{W_NS}}}fldChar')
            )
            has_instr = any(True for _ in child.iter(f'{{{W_NS}}}instrText'))
            # Это последний пустой абзац с только end
            if has_end and not has_instr:
                toc_end_para_idx = i
                # Проверяем, что следующий параграф уже не toc-стиль
                break
        # Если не нашли чистый END — последний TOC-стиль параграф + 1
        if toc_end_para_idx is None:
            for i in range(toc_field_para_idx, min(toc_field_para_idx + 50, len(children))):
                child = children[i]
                if child.tag != f'{{{W_NS}}}p':
                    continue
                pPr = child.find(f'{{{W_NS}}}pPr')
                pstyle_val = ''
                if pPr is not None:
                    pst = pPr.find(f'{{{W_NS}}}pStyle')
                    if pst is not None:
                        pstyle_val = pst.get(f'{{{W_NS}}}val', '')
                if pstyle_val not in ('12', '20', '30', '40'):
                    toc_end_para_idx = i
                    break

        print(f'TOC field para: {toc_field_para_idx}, TOC end para: {toc_end_para_idx}')

        # Удаляем старые кеш-записи TOC:
        # все TOC-стилевые параграфы в диапазоне (toc_field_para_idx, toc_end_para_idx)
        to_remove = []
        for i in range(toc_field_para_idx + 1, toc_end_para_idx):
            child = children[i]
            if child.tag != f'{{{W_NS}}}p':
                continue
            pPr = child.find(f'{{{W_NS}}}pPr')
            if pPr is not None:
                pst = pPr.find(f'{{{W_NS}}}pStyle')
                if pst is not None and pst.get(f'{{{W_NS}}}val', '') in ('12','20','30','40'):
                    to_remove.append(child)
        for el in to_remove:
            body_el.remove(el)

        # Также чистим содержимое после fldChar separate в toc_field_para_idx параграфе
        # (убираем старую первую запись, которая была вшита в тот же параграф)
        field_para = list(body_el)[toc_field_para_idx]
        after_sep  = False
        runs_to_del = []
        hlinks_to_del = []
        for child in list(field_para):
            tag = child.tag.split('}')[-1] if '}' in child.tag else child.tag
            if not after_sep:
                # Ищем fldChar separate
                for fc in child.iter(f'{{{W_NS}}}fldChar'):
                    if fc.get(f'{{{W_NS}}}fldCharType') == 'separate':
                        after_sep = True
                        break
            else:
                # Всё после separate — старая кеш-запись
                if tag in ('r', 'hyperlink', 'bookmarkStart', 'bookmarkEnd'):
                    runs_to_del.append(child)
        for r in runs_to_del:
            field_para.remove(r)

        # Вставляем новые TOC-записи после toc_field_para_idx
        # (toc_end_para_idx сдвинулся из-за удалений — пересчитываем)
        children_now = list(body_el)
        # Вставляем перед toc_end_para — находим его заново
        # Ищем параграф с fldChar end без instrText после нашего поля
        insert_before_el = None
        for child in children_now[toc_field_para_idx + 1:]:
            if child.tag != f'{{{W_NS}}}p':
                continue
            has_end = any(
                fc.get(f'{{{W_NS}}}fldCharType') == 'end'
                for fc in child.iter(f'{{{W_NS}}}fldChar')
            )
            has_instr = any(True for _ in child.iter(f'{{{W_NS}}}instrText'))
            if has_end and not has_instr:
                insert_before_el = child
                break
        if insert_before_el is None:
            # Fallback: вставляем в конец body перед sectPr
            insert_before_el = body_el.find(f'{{{W_NS}}}sectPr')

        for toc_level, text, bm_name in headings:
            new_p = etree.fromstring(_make_toc_para_xml(toc_level, text, bm_name))
            insert_before_el.addprevious(new_p)

    # ── 3. settings.xml: updateFields ────────────────────────────────────────
    settings_root = etree.fromstring(files['word/settings.xml'])
    # Удаляем старый updateFields если есть
    for old in settings_root.findall(f'{{{W_NS}}}updateFields'):
        settings_root.remove(old)
    uf = etree.SubElement(settings_root, f'{{{W_NS}}}updateFields')
    uf.set(f'{{{W_NS}}}val', '1')
    files['word/settings.xml'] = etree.tostring(
        settings_root, xml_declaration=True, encoding='UTF-8', standalone=True
    )

    # ── Записываем обратно ────────────────────────────────────────────────────
    # document.xml нужно сериализовать с сохранением namespaces
    files['word/document.xml'] = etree.tostring(
        doc_root, xml_declaration=True, encoding='UTF-8', standalone=True
    )

    tmp2 = docx_path.with_suffix('.tmp2.docx')
    with zipfile.ZipFile(tmp2, 'w', zipfile.ZIP_DEFLATED) as zout:
        for name, data in files.items():
            zout.writestr(name, data)
    tmp2.replace(docx_path)
    print(f'TOC rebuilt, updateFields=1, saved: {docx_path}')


