_headings = []   # [(toc_level, display_text, bookmark_name)]
_bm_id    = [2000]  # ID закладок — начинаем с 2000 чтобы не конфликтовать с шаблоном

def _add_bookmark(para, toc_level, text):
    """Вставляет bookmarkStart/End в абзац и запоминает его для TOC."""
    bm_id   = _bm_id[0]; _bm_id[0] += 1
    bm_name = f'_TocBK{bm_id}'

    pel = para._p
    bms = OxmlElement('w:bookmarkStart')
    bms.set(qn('w:id'),   str(bm_id))
    bms.set(qn('w:name'), bm_name)
    bme = OxmlElement('w:bookmarkEnd')
    bme.set(qn('w:id'),   str(bm_id))

    # bookmarkStart — перед первым дочерним элементом
    pel.insert(0, bms)
    # bookmarkEnd — после последнего run
    pel.append(bme)

    _headings.append((toc_level, text, bm_name))
    return bm_name

